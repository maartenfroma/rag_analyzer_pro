from docx import Document
from datetime import datetime
from io import BytesIO

class DocxExporter:
    # Helper class to export chat history to DOCX format

    @staticmethod
    def export(chat_history, file_path=None, doc_title=None, chunk_count =None, file_size=None):
        
        # Check if chat history is empty and return early if so
        if not chat_history:
            return

        # Create a new DOCX document for exporting chat history
        document = Document()
        
        # Add a heading for the chat history section
        if doc_title:
            document.add_heading(doc_title or "RAG Analyzer Pro Report",
            level=1)
        else:
            document.add_heading("Chat History", level=1)

        # Add a paragraph indicating the purpose of the document
        document.add_paragraph("AI-Powered Document Analysis")

        # Add metadata about the document, such as generation time, title, chunk count, and file size if provided
        document.add_paragraph(
            f"Generated: {datetime.now():%d-%m-%Y %H:%M}"
        )
        
        # Add a blank line for better readability
        if doc_title:
            document.add_paragraph(
                f"Document: {doc_title}"
            )
            
        # Add a blank line for better readability
        if chunk_count is not None:
            document.add_paragraph(
                f"Chunk Count: {chunk_count}"
            )
            
        # Add a blank line for better readability
        if file_size is not None:
            document.add_paragraph(
                f"File Size: {round(file_size / (1024 * 1024), 2)} MB"
            )
            
        # Add a blank line for better readability before questions analyzed
        document.add_paragraph(
            f"Questions Analyzed: {len(chat_history)}"
        )
        
        document.add_page_break()
        
        for entry in chat_history:
            # Add a page break before each new question-answer pair for better readability
            # Add a heading for each question-answer pair for better readability
            document.add_heading(
                "Question",
                level=2
            )

            document.add_paragraph(
                entry.get("query", "")
            )

            document.add_heading(
                "Answer",
                level=2
            )

            document.add_paragraph(
                entry.get("response", "")
            )

            document.add_paragraph(
                f"Sources Used: {len(entry.get('metadata', []))}"
            )

            document.add_paragraph("-" * 40)

        document.add_paragraph(
            "Generated by RAG Analyzer Pro"
        )
            
        buffer = BytesIO()
        document.save(buffer)
        buffer.seek(0)
    
            
        # Return the content of the DOCX file as bytes
        return buffer.getvalue()